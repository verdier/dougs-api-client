/**
 * Maps is* flags to OperationType array.
 */
function extractTypes(raw: RawOperationDTO): OperationType[] {
    const typeMap: Record<string, OperationType> = {
        isBank: 'bank',
        isCustomerCreditNote: 'customerCreditNote',
        isSupplierCreditNote: 'supplierCreditNote',
        isExpense: 'expense',
        isInvoice: 'invoice',
        isClientInvoice: 'clientInvoice',
        isVendorInvoice: 'vendorInvoice',
        isInvoiceSupplier: 'invoiceSupplier',
        isInvoiceCustomer: 'invoiceCustomer',
        isKilometricIndemnity: 'kilometricIndemnity',
        isCashPayment: 'cashPayment',
        isCashExpense: 'cashExpense',
        isMiscellaneous: 'miscellaneous',
        isCustomerEditableMiscellaneous: 'customerEditableMiscellaneous',
        isAccountingSurveyMiscellaneous: 'accountingSurveyMiscellaneous',
        isDispatch: 'dispatch',
        isReconciliation: 'reconciliation',
        isCashRegisterDispatch: 'cashRegisterDispatch',
        isCashRegisterFee: 'cashRegisterFee',
    };

    const types: OperationType[] = [];
    for (const [flag, typeName] of Object.entries(typeMap)) {
        if ((raw as any)[flag] === true) {
            types.push(typeName);
        }
    }
    return types;
}

/**
 * Maps raw source document attachment to SourceDocumentAttachmentDTO.
 */
function mapSourceDocumentAttachment(raw: RawSourceDocumentAttachmentDTO): SourceDocumentAttachmentDTO {
    return {
        id: raw.id,
        url: raw.url,
        filename: raw.filename,
        mimeType: raw.mimeType,
        size: raw.size,
        createdAt: raw.createdAt,
    };
}

/**
 * Maps raw breakdown to simplified BreakdownDTO.
 */
function mapBreakdown(raw: RawBreakdownDTO): BreakdownDTO {
    return {
        id: raw.id,
        amount: raw.amount,
        categoryId: raw.categoryId,
        categoryWording: raw.categoryWording,
        categoryGroup: raw.categoryGroup ? {
            id: raw.categoryGroup.id,
            name: raw.categoryGroup.name,
            color: raw.categoryGroup.color,
        } : undefined,
        wording: raw.wording ?? undefined,
        isInbound: raw.isInbound,
        isCounterpart: raw.isCounterpart,
        hasVat: raw.hasVat,
        vatAmount: raw.vatAmount,
        vatRate: raw.vatRate ?? undefined,
    };
}

/**
 * Maps raw API response to filtered OperationDTO.
 */
export function mapOperation(raw: RawOperationDTO): OperationDTO {
    return {
        id: raw.id,
        companyId: raw.companyId,
        transactionId: raw.transactionId,
        date: raw.date,
        amount: raw.amount,
        totalAmount: raw.totalAmount,
        wording: raw.wording,
        name: raw.name,
        memo: raw.memo,
        description: raw.description,

        deleted: raw.deleted,
        isDraft: raw.isDraft,
        autogenerated: raw.autogenerated,
        validated: raw.validated,
        validatedAt: raw.validatedAt,
        excluded: raw.excluded,
        exclusionReason: raw.exclusionReason,
        message: raw.message,
        errors: raw.errors,

        type: raw.type,
        types: extractTypes(raw),
        isInbound: raw.isInbound,

        hasVat: raw.hasVat,
        vatAmount: raw.vatAmount,
        vatRate: raw.vatRate,

        creatorId: raw.creatorId,
        createdAt: raw.createdAt,
        updatedAt: raw.updatedAt,

        breakdowns: raw.breakdowns?.map(mapBreakdown),

        sourceDocumentAttachments: raw.sourceDocumentAttachments?.map(mapSourceDocumentAttachment),
        sourceDocumentCandidate: raw.sourceDocumentCandidate,
    };
}

/**
 * Maps an array of raw API responses to filtered OperationDTO array.
 */
export function mapOperations(raw: RawOperationDTO[]): OperationDTO[] {
    return raw.map(mapOperation);
}
