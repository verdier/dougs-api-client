import { actions, Client } from "../src";

const BASE_URL = "https://app.dougs.fr";
const COMPANY_ID = 101;
const OPERATION_ID = 701;

function client(): Client {
    return new Client({ email: "test@example.invalid", password: "not-a-real-password", baseUrl: BASE_URL, cookies: ["session=synthetic"] });
}
function json(value: unknown): Response {
    return new Response(JSON.stringify(value), { headers: { "content-type": "application/json" } });
}
function operation(overrides: Record<string, unknown> = {}): Record<string, unknown> {
    return {
        id: OPERATION_ID, companyId: COMPANY_ID, deleted: false, excluded: false, autogenerated: false,
        type: "vendorInvoice", date: "2025-01-15", amount: 50, isInbound: false, isDraft: false,
        validated: false, hasVat: false,
        breakdowns: [{
            id: 801, amount: 50, categoryId: 901, categoryWording: "Original", isInbound: false,
            isCounterpart: false, hasVat: false,
            associations: [{ name: "investment", slots: {
                investment: { key: "dynamicInvestmentRecord", type: "record", isAssignable: true },
            } }],
        }],
        ...overrides,
    };
}

describe("breakdown association candidate reads", () => {
    const realFetch = global.fetch;
    let fetchMock: jest.Mock;
    beforeEach(() => { fetchMock = jest.fn(); global.fetch = fetchMock as unknown as typeof fetch; });
    afterEach(() => { global.fetch = realFetch; });

    test("preflights the scoped server metadata and returns only curated candidates", async () => {
        fetchMock.mockResolvedValueOnce(json(operation())).mockResolvedValueOnce(json({
            descriptor: { fallbackToCreation: true, private: "omit" },
            items: [{ value: 123, label: "Asset", description: "2025", internal: "omit" }],
            preferredItems: [{ value: 456, label: "Preferred", internal: "omit" }],
            private: "omit",
        }));

        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment", "investment", { offset: 0, limit: 100 },
        )).resolves.toEqual({
            descriptor: { fallbackToCreation: true },
            items: [{ value: 123, label: "Asset", description: "2025" }],
            preferredItems: [{ value: 456, label: "Preferred", description: undefined }],
        });
        expect(String(fetchMock.mock.calls[1][0])).toBe(
            `${BASE_URL}/companies/${COMPANY_ID}/operations/${OPERATION_ID}/breakdowns/801/associations/investment/slots/investment/candidates?offset=0&limit=100`,
        );
    });

    test("canonicalizes candidate strings and rejects whitespace-normalized duplicates", async () => {
        fetchMock.mockResolvedValueOnce(json(operation())).mockResolvedValueOnce(json({
            descriptor: {}, items: [{ value: "  asset-1  ", label: "  Asset  ", description: "  2025  " }], preferredItems: [],
        }));
        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment", "investment", { offset: 0 },
        )).resolves.toMatchObject({ items: [{ value: "asset-1", label: "Asset", description: "2025" }] });

        fetchMock.mockClear();
        fetchMock.mockResolvedValueOnce(json(operation())).mockResolvedValueOnce(json({
            descriptor: {}, items: [{ value: "asset-1" }], preferredItems: [{ value: " asset-1 " }],
        }));
        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment", "investment", { offset: 0 },
        )).rejects.toThrow("Invalid breakdown association candidates response");
    });

    test("encodes dynamic route components after metadata preflight", async () => {
        const raw = operation({ breakdowns: [{
            ...(operation().breakdowns as any[])[0],
            associations: [{ name: "investment / special", slots: {
                "record/value": { key: "dynamic", type: "record", isAssignable: true },
            } }],
        }] });
        fetchMock.mockResolvedValueOnce(json(raw)).mockResolvedValueOnce(json({ descriptor: {}, items: [], preferredItems: [] }));

        await client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment / special", "record/value", { offset: 0 },
        );
        expect(String(fetchMock.mock.calls[1][0])).toBe(
            `${BASE_URL}/companies/${COMPANY_ID}/operations/${OPERATION_ID}/breakdowns/801/associations/investment%20%2F%20special/slots/record%2Fvalue/candidates?offset=0`,
        );
    });

    test.each([
        [".", "investment"],
        ["investment", ".."],
        [" . ", "investment"],
    ])("rejects dot route segments %s / %s before any request", async (associationName, slotName) => {
        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, associationName, slotName, { offset: 0 },
        )).rejects.toThrow("Invalid");
        expect(fetchMock).not.toHaveBeenCalled();
    });

    test("rejects unknown candidate query keys at runtime before any request", async () => {
        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment", "investment", { offset: 0, unexpected: true } as any,
        )).rejects.toThrow("Invalid breakdown association candidates query");
        expect(fetchMock).not.toHaveBeenCalled();
    });

    test.each([
        [operation({ breakdowns: [
            ...(operation().breakdowns as any[]),
            { ...(operation().breakdowns as any[])[0] },
        ] }), "duplicate breakdown IDs"],
        [operation({ breakdowns: [{
            ...(operation().breakdowns as any[])[0],
            associations: [
                ...(operation().breakdowns as any[])[0].associations,
                ...(operation().breakdowns as any[])[0].associations,
            ],
        }] }), "ambiguous associations"],
        [operation({ id: OPERATION_ID + 1 }), "wrong operation scope"],
        [operation({ breakdowns: [{ ...(operation().breakdowns as any[])[0], companyId: COMPANY_ID + 1 }] }), "wrong breakdown scope"],
    ])("rejects %s without reaching the candidate route", async (raw) => {
        fetchMock.mockResolvedValueOnce(json(raw));
        await expect(client().api.operations({ companyId: COMPANY_ID }).getBreakdownAssociationCandidates(
            OPERATION_ID, 801, "investment", "investment", { offset: 0 },
        )).rejects.toThrow();
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("exposes one strict read-only action contract", () => {
        expect(actions.operations_get_breakdown_association_candidates.safety).toEqual({
            readOnly: true, destructive: false, idempotent: true, openWorld: true,
        });
        expect(actions.operations_get_breakdown_association_candidates.inputSchema.safeParse({
            companyId: COMPANY_ID, operationId: OPERATION_ID, breakdownId: 801,
            associationName: "investment", slotName: "investment", offset: 0, extra: true,
        }).success).toBe(false);
    });
});
