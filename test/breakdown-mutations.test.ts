import { Client } from "../src";

const BASE_URL = "https://app.dougs.fr";
const COMPANY_ID = 101;
const OPERATION_ID = 701;
const UPDATED_AT = "2026-08-04T12:00:00.000Z";

function client(operationMemoTag?: string): Client {
    return new Client({ email: "test@example.invalid", password: "not-a-real-password", baseUrl: BASE_URL, cookies: ["session=synthetic"], operationMemoTag });
}
function json(value: unknown): Response {
    return new Response(JSON.stringify(value), { headers: { "content-type": "application/json" } });
}
function line(overrides: Record<string, unknown> = {}): Record<string, unknown> {
    return {
        id: 801, amount: 10.01, categoryId: 20, categoryWording: "Supplies", isInbound: false,
        isCounterpart: false, isFee: false, hasVat: false, section: "main", associationData: { partnerId: 33 },
        ...overrides,
    };
}
function operation(breakdowns = [line()], overrides: Record<string, unknown> = {}): Record<string, unknown> {
    return {
        id: OPERATION_ID, companyId: COMPANY_ID, deleted: false, excluded: false, autogenerated: false,
        type: "expense", date: "2026-08-04", amount: 10.01, totalAmount: 10.01,
        isInbound: false, isDraft: false, validated: false, validatedAt: null, manuallyLocked: false,
        lockedByDate: false, hasVat: false, isTotalAmountValid: true, updatedAt: UPDATED_AT,
        memo: "unchanged #jarvis", sourceDocumentAttachments: [], sections: [{ id: "main", invertSign: false }],
        breakdowns, ...overrides,
    };
}

describe("live-proven breakdown mutations", () => {
    const realFetch = global.fetch;
    let fetchMock: jest.Mock;
    beforeEach(() => { fetchMock = jest.fn(); global.fetch = fetchMock as unknown as typeof fetch; });
    afterEach(() => { global.fetch = realFetch; });

    test.each([
        ["empty", "", "#jarvis"],
        ["existing", "Historical memo", "Historical memo #jarvis"],
        ["already tagged", "Historical memo #jarvis", "Historical memo #jarvis"],
    ])("tags a %s memo for a line mutation exactly once", async (_name, memo, expectedMemo) => {
        const before = operation([line({ amount: 0 })], { memo });
        const persisted = operation([line({ amount: 6 })], {
            memo: expectedMemo, totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client("jarvis").api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).resolves.toMatchObject({ id: OPERATION_ID });
        expect(JSON.parse(fetchMock.mock.calls[1][1].body).memo).toBe(expectedMemo);
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("rejects a provider response that drops the required memo tag after one POST", async () => {
        const before = operation([line({ amount: 0 })], { memo: "Historical memo" });
        const persisted = operation([line({ amount: 6 })], {
            memo: "Historical memo", totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client("jarvis").api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("BREAKDOWN_MUTATION_UNVERIFIED_POST");
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("preserves a memo exactly when no tag is configured", async () => {
        const before = operation([line({ amount: 0 })], { memo: "Historical memo" });
        const persisted = operation([line({ amount: 6 })], {
            memo: "Historical memo", totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).resolves.toMatchObject({ id: OPERATION_ID });
        expect(JSON.parse(fetchMock.mock.calls[1][1].body).memo).toBe("Historical memo");
    });

    test("adds only a zero-residual UI detail and verifies its provider ID", async () => {
        const before = operation();
        const persisted = operation([...(before.breakdowns as any[]), line({ id: 802, amount: 0, categoryId: -1, categoryWording: "Non catégorisé" })]);
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).addBreakdownDetail(OPERATION_ID, { expectedUpdatedAt: UPDATED_AT })).resolves.toMatchObject({ id: OPERATION_ID });
        const payload = JSON.parse(fetchMock.mock.calls[1][1].body);
        expect(payload.updatedBreakdown).toEqual({ categoryWording: "Non catégorisé", section: "main", amount: 0, isInbound: false });
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("requires contextual category eligibility then final version GET before one category POST", async () => {
        const before = operation();
        const persisted = operation([line({ categoryId: 169, categoryWording: "Local fitout", resolvedCategoryId: 169 })]);
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json([169]))
            .mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await client().api.operations({ companyId: COMPANY_ID }).setBreakdownCategory(OPERATION_ID, 801, 169, { expectedUpdatedAt: UPDATED_AT });
        expect(String(fetchMock.mock.calls[1][0])).toContain(`/operations/${OPERATION_ID}/breakdowns/801/available-categories`);
        expect(JSON.parse(fetchMock.mock.calls[3][1].body).updatedBreakdown.categoryId).toBe(169);
        expect(fetchMock).toHaveBeenCalledTimes(5);
    });

    test("accepts category-derived association metadata for an uncategorized zero line", async () => {
        const before = operation([line({
            amount: 0, categoryId: -1, categoryWording: "Non catégorisé",
            associationData: undefined, associations: undefined,
        })], { amount: 0, totalAmount: 0 });
        const persisted = operation([line({
            amount: 0, categoryId: 169, categoryWording: "Local fitout",
            associationData: { isInvestment: false },
            associations: [{ name: "investment", slots: { investment: { key: "isInvestment", type: "boolean" } } }],
        })], { amount: 0, totalAmount: 0 });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json([169]))
            .mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownCategory(
            OPERATION_ID, 801, 169, { expectedUpdatedAt: UPDATED_AT },
        )).resolves.toMatchObject({ id: OPERATION_ID });
    });

    test.each([
        ["partner associationData drift", line({ categoryId: 169, associationData: { partnerId: 34 } })],
        ["other associationData drift", line({ categoryId: 169, associationData: { partnerId: 33, taxProfile: "changed" } })],
        ["amount drift", line({ categoryId: 169, amount: 9.99 })],
        ["direction drift", line({ categoryId: 169, isInbound: true })],
        ["VAT drift", line({ categoryId: 169, hasVat: true })],
        ["section drift", line({ categoryId: 169, section: "other" })],
    ])("rejects category response with %s", async (_name, target) => {
        const before = operation();
        const persisted = operation([target]);
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json([169]))
            .mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownCategory(
            OPERATION_ID, 801, 169, { expectedUpdatedAt: UPDATED_AT },
        )).rejects.toThrow("BREAKDOWN_MUTATION_UNVERIFIED_POST");
        expect(fetchMock).toHaveBeenCalledTimes(5);
    });

    test("accepts provider-recalculated amount presentation fields", async () => {
        const before = operation([line({ amount: 0, quantity: 2, unitAmount: 0, amountExcludingTaxesWithRecoverageRate: 0 })]);
        const persisted = operation([line({ amount: 6, quantity: 2, unitAmount: 3, amountExcludingTaxesWithRecoverageRate: 6 })], {
            totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).resolves.toMatchObject({ id: OPERATION_ID });
    });

    test.each([
        ["associationData drift", { associationData: { partnerId: 34 } }],
        ["associations drift", { associations: [{ name: "investment" }] }],
        ["category drift", { categoryId: 21 }],
        ["direction drift", { isInbound: true }],
        ["VAT input drift", { hasVat: true }],
        ["section drift", { section: "other" }],
        ["quantity drift", { quantity: 1 }],
        ["unexpected non-derived money metadata", { manualVatAmount: 1 }],
        ["primary amount mismatch", { amount: 5 }],
    ])("rejects amount response with %s", async (_name, overrides) => {
        const before = operation([line({ amount: 0, quantity: 2, associations: [{ name: "partner" }] })]);
        const persisted = operation([line({ amount: 6, quantity: 2, associations: [{ name: "partner" }], ...overrides })], {
            totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("BREAKDOWN_MUTATION_UNVERIFIED_POST");
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("allows an intentional intermediate imbalance and verifies exact cents", async () => {
        const before = operation([line({ id: 801, amount: 0, categoryId: 169 }), line({ id: 802, amount: 10.01, isCounterpart: true, isInbound: true })]);
        const persisted = operation([line({ id: 801, amount: 6, categoryId: 169 }), line({ id: 802, amount: 10.01, isCounterpart: true, isInbound: true })], {
            totalAmount: 16.01, isTotalAmountValid: false,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        });
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("rejects an incorrect declared amount result before POST", async () => {
        const before = operation([line({ id: 801, amount: 0, categoryId: 169 }), line({ id: 802, amount: 10.01, isCounterpart: true, isInbound: true })]);
        fetchMock.mockResolvedValueOnce(json(before));

        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 6, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("Expected total declaration");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("rejects an incorrect declared removal result before POST", async () => {
        const removable = line({ id: 802, amount: 6 });
        fetchMock.mockResolvedValueOnce(json(operation([line({ amount: 4.01 }), removable])));
        await expect(client().api.operations({ companyId: COMPANY_ID }).removeBreakdownDetail(OPERATION_ID, 802, {
            expectedTotalAmount: 4.02, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("Expected total declaration");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("accepts a separately authorized balancing repair after an invalid intermediate state", async () => {
        const before = operation([line({ amount: 6 }), line({ id: 802, amount: 10.01, isCounterpart: true, isInbound: true })], {
            amount: 20.01, totalAmount: 16.01, isTotalAmountValid: false,
        });
        const persisted = operation([line({ amount: 10 }), line({ id: 802, amount: 10.01, isCounterpart: true, isInbound: true })], {
            amount: 20.01, totalAmount: 20.01, isTotalAmountValid: true,
        });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));
        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 10, expectedTotalAmount: 20.01, expectedIsTotalAmountValid: true, expectedUpdatedAt: UPDATED_AT,
        })).resolves.toMatchObject({ id: OPERATION_ID });
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("rejects malformed counterpart metadata before POST", async () => {
        fetchMock.mockResolvedValueOnce(json(operation([line({ isCounterpart: undefined })])));
        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 6, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("Counterpart and fee");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test.each([
        ["an extra breakdown", operation([line({ amount: 6 }), line({ id: 802, amount: 0 })], { totalAmount: 16.01, isTotalAmountValid: false })],
        ["target counterpart drift", operation([line({ amount: 6, isCounterpart: true })], { totalAmount: 16.01, isTotalAmountValid: false })],
        ["top-level type drift", operation([line({ amount: 6 })], { type: "different", totalAmount: 16.01, isTotalAmountValid: false })],
    ])("rejects %s after exactly one POST", async (_name, persisted) => {
        const before = operation([line({ amount: 0 })]);
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));
        await expect(client().api.operations({ companyId: COMPANY_ID }).setBreakdownAmount(OPERATION_ID, 801, {
            amount: 6, expectedTotalAmount: 16.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("BREAKDOWN_MUTATION_UNVERIFIED_POST");
        expect(fetchMock).toHaveBeenCalledTimes(3);
    });

    test("changes only the dynamically exposed isInvestment boolean", async () => {
        const association = [{ name: "investment", slots: { investment: { key: "isInvestment", type: "boolean", isAssignable: true } } }];
        const before = operation([line({ associations: association })]);
        const persisted = operation([line({ associations: association, associationData: { partnerId: 33, isInvestment: true } })]);
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json(before))
            .mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await client().api.operations({ companyId: COMPANY_ID }).setBreakdownIsInvestment(OPERATION_ID, 801, true, { expectedUpdatedAt: UPDATED_AT });
        expect(fetchMock).toHaveBeenCalledTimes(4);
    });

    test("removes a detail but forbids removing the last business line", async () => {
        const removable = line({ id: 802, amount: 6, categoryId: 169 });
        const before = operation([line({ amount: 4.01 }), removable]);
        const persisted = operation([line({ amount: 4.01 })], { totalAmount: 4.01, isTotalAmountValid: false });
        fetchMock.mockResolvedValueOnce(json(before)).mockResolvedValueOnce(json({})).mockResolvedValueOnce(json(persisted));

        await client().api.operations({ companyId: COMPANY_ID }).removeBreakdownDetail(OPERATION_ID, 802, {
            expectedTotalAmount: 4.01, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        });
        expect(JSON.parse(fetchMock.mock.calls[1][1].body).updatedBreakdown.id).toBe(802);

        fetchMock.mockClear();
        fetchMock.mockResolvedValueOnce(json(operation([line()])));
        await expect(client().api.operations({ companyId: COMPANY_ID }).removeBreakdownDetail(OPERATION_ID, 801, {
            expectedTotalAmount: 0, expectedIsTotalAmountValid: false, expectedUpdatedAt: UPDATED_AT,
        })).rejects.toThrow("last business");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });
});
