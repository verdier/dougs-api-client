import { actions, appendOperationMemoTag, Client } from "../src";
import { EXPENSE_REPORT_UNVERIFIED_POST } from "../src/mutation-errors";

const BASE_URL = "https://app.dougs.fr";
const COMPANY_ID = 101;

function client(tag?: string): Client {
    return new Client({
        email: "test@example.invalid", password: "not-a-real-password", baseUrl: BASE_URL,
        cookies: ["session=synthetic"], operationMemoTag: tag,
    });
}

function json(value: unknown): Response {
    return new Response(JSON.stringify(value), { headers: { "content-type": "application/json" } });
}

function report(data: { memo: string; breakdowns: Array<{ amount: number; categoryId: number }> }, overrides: Record<string, unknown> = {}): Record<string, unknown> {
    const total = data.breakdowns.reduce((sum, line) => sum + line.amount, 0);
    return {
        id: 701, companyId: COMPANY_ID, deleted: false, autogenerated: false,
        type: "expense", date: "2025-01-15", memo: data.memo, amount: total, totalAmount: total,
        isInbound: false, isDraft: false, validated: false, validatedAt: null,
        lockedByDate: false, manuallyLocked: false, needsAttention: false,
        allowUnbalanced: false, isTotalAmountValid: true, errors: [], message: null,
        excluded: false, hasVat: false,
        breakdowns: [
            ...data.breakdowns.map((line, index) => ({
                id: 801 + index, ...line, isInbound: false, isCounterpart: false, hasVat: false,
                categoryWording: "Synthetic business",
            })),
            {
                id: 900, amount: total, categoryId: 9999, isInbound: true, isCounterpart: true,
                hasVat: false, categoryWording: "Provider counterpart", associationData: { partnerId: 1001 },
            },
        ],
        ...overrides,
    };
}

function kilometric(memo: string | undefined): Record<string, unknown> {
    return {
        id: 702, companyId: COMPANY_ID, deleted: false, autogenerated: false,
        type: "kilometricIndemnity", date: "2025-01-15", memo, amount: 0, isInbound: false,
        isDraft: false, hasVat: false,
        breakdowns: [{
            id: 803, amount: 0, categoryId: -1, isInbound: false, isCounterpart: false,
            hasVat: false, categoryWording: "Kilometric", associationData: { kilometers: 12 },
        }],
    };
}

describe("operation memo tag", () => {
    test("does nothing without a tag and appends exactly one terminal valid tag", () => {
        expect(appendOperationMemoTag("Memo", undefined)).toBe("Memo");
        expect(appendOperationMemoTag("", undefined)).toBe("");
        expect(appendOperationMemoTag(null, undefined)).toBeNull();
        expect(appendOperationMemoTag("", "#jarvis")).toBe("#jarvis");
        expect(appendOperationMemoTag(null, "#jarvis")).toBe("#jarvis");
        expect(appendOperationMemoTag("Memo", "#jarvis")).toBe("Memo #jarvis");
        expect(appendOperationMemoTag("Memo #jarvis", "#jarvis")).toBe("Memo #jarvis");
        expect(appendOperationMemoTag("Memo #jarvis extra #jarvis", "#jarvis")).toBe("Memo #jarvis extra #jarvis");
        expect(appendOperationMemoTag("Taxi (#jarvis) Paris", "#jarvis")).toBe("Taxi (#jarvis) Paris #jarvis");
        expect(appendOperationMemoTag("Taxi #jarvis, Paris", "#jarvis")).toBe("Taxi #jarvis, Paris #jarvis");
    });

    test("rejects invalid config tags and a final memo that would overflow", () => {
        for (const operationMemoTag of ["", "#jarvis", "has space", "a".repeat(33)]) {
            expect(() => client(operationMemoTag)).toThrow("Operation memo tag");
        }
        expect(() => appendOperationMemoTag("x".repeat(1_993), "#jarvis"))
            .toThrow("Operation memo exceeds");
    });

    test("applies the configured tag to both expense and kilometric writes", async () => {
        const realFetch = global.fetch;
        const fetchMock = jest.fn()
            .mockResolvedValueOnce(json([901]))
            .mockResolvedValueOnce(json([{ id: 1001, companyId: COMPANY_ID }]))
            .mockResolvedValueOnce(json(report({ memo: "Expense #jarvis", breakdowns: [{ amount: 42.5, categoryId: 901 }] })))
            .mockResolvedValueOnce(json(report({ memo: "Expense #jarvis", breakdowns: [{ amount: 42.5, categoryId: 901 }] })))
            .mockResolvedValueOnce(json(kilometric("Trip #jarvis")));
        global.fetch = fetchMock as unknown as typeof fetch;
        try {
            await client("jarvis").api.operations({ companyId: COMPANY_ID }).createExpense({
                date: "2025-01-15", amount: 42.5, memo: "Expense", businessCategoryId: 901, partnerId: 1001,
            });
            await client("jarvis").api.operations({ companyId: COMPANY_ID }).createKilometricIndemnity({
                date: "2025-01-15", distance: 12, memo: "Trip",
            });
            expect(JSON.parse(fetchMock.mock.calls[2][1].body).memo).toBe("Expense #jarvis");
            expect(JSON.parse(fetchMock.mock.calls[4][1].body).memo).toBe("Trip #jarvis");
        } finally {
            global.fetch = realFetch;
        }
    });
});

describe("multi-line expense reports", () => {
    const data = {
        date: "2025-01-15", memo: "Multi", partnerId: 1001,
        businessBreakdowns: [{ amount: 4.01, categoryId: 901 }, { amount: 6, categoryId: 902 }],
    };
    const realFetch = global.fetch;
    let fetchMock: jest.Mock;

    beforeEach(() => {
        fetchMock = jest.fn();
        global.fetch = fetchMock as unknown as typeof fetch;
    });
    afterEach(() => { global.fetch = realFetch; });

    test("preflights once, posts the derived exact body, and accepts reordered provider lines", async () => {
        const persisted = report({ memo: "Multi", breakdowns: [...data.businessBreakdowns].reverse() });
        fetchMock
            .mockResolvedValueOnce(json([901, 902]))
            .mockResolvedValueOnce(json([{ id: 1001, companyId: COMPANY_ID }]))
            .mockResolvedValueOnce(json(persisted))
            .mockResolvedValueOnce(json(persisted));

        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(data)).resolves.toMatchObject({ id: 701 });
        expect(JSON.parse(fetchMock.mock.calls[2][1].body)).toEqual({
            type: "expense", date: data.date, memo: data.memo, amount: 10.01, attachments: [],
            breakdowns: [
                { amount: 4.01, categoryId: 901 }, { amount: 6, categoryId: 902 },
                { amount: 0, categoryId: -1, isCounterpart: true, associationData: { partnerId: 1001 } },
            ],
        });
    });

    test("accepts a structurally verified POST without coherence fields only after a coherent fresh GET", async () => {
        const post = report({ memo: "Multi", breakdowns: data.businessBreakdowns }, {
            isDraft: undefined, validated: undefined, validatedAt: undefined,
            lockedByDate: undefined, manuallyLocked: undefined, needsAttention: undefined,
            allowUnbalanced: undefined, isTotalAmountValid: undefined, errors: undefined, message: undefined,
        });
        fetchMock
            .mockResolvedValueOnce(json([901, 902]))
            .mockResolvedValueOnce(json([{ id: 1001, companyId: COMPANY_ID }]))
            .mockResolvedValueOnce(json(post))
            .mockResolvedValueOnce(json(report({ memo: "Multi", breakdowns: data.businessBreakdowns })));

        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(data)).resolves.toMatchObject({ id: 701 });
        expect(fetchMock.mock.calls.map(([url]) => String(url))).toEqual([
            `${BASE_URL}/companies/${COMPANY_ID}/categories?type=expense&operationDate=2025-01-15&amount=10.01`,
            `${BASE_URL}/companies/${COMPANY_ID}/partners`,
            `${BASE_URL}/companies/${COMPANY_ID}/operations`,
            `${BASE_URL}/companies/${COMPANY_ID}/operations/701`,
        ]);
    });

    test("returns static no-retry when persisted GET coherence fails without replaying POST", async () => {
        fetchMock
            .mockResolvedValueOnce(json([901, 902]))
            .mockResolvedValueOnce(json([{ id: 1001, companyId: COMPANY_ID }]))
            .mockResolvedValueOnce(json(report({ memo: "Multi", breakdowns: data.businessBreakdowns })))
            .mockResolvedValueOnce(json(report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { errors: ["bad"] })));

        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(data))
            .rejects.toThrow(EXPENSE_REPORT_UNVERIFIED_POST);
        expect(fetchMock.mock.calls.filter(([, init]) => init.method === "POST")).toHaveLength(1);
        expect(fetchMock).toHaveBeenCalledTimes(4);
    });

    test.each([
        [{ ...data, businessBreakdowns: [{ amount: 1.001, categoryId: 901 }] }],
        [{ ...data, businessBreakdowns: [{ amount: 1, categoryId: 901 }, { amount: 1, categoryId: 901 }] }],
        [{ ...data, businessBreakdowns: [{ amount: 100000, categoryId: 901 }, { amount: 0.01, categoryId: 902 }] }],
    ])("rejects invalid totals or duplicate categories without any request", async (input) => {
        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(input))
            .rejects.toThrow("Invalid expense report creation data");
        expect(fetchMock).not.toHaveBeenCalled();
    });

    test.each([
        [[902], [{ id: 1001, companyId: COMPANY_ID }], "Expense category is not available"],
        [[901, 902], [{ id: 1001, companyId: COMPANY_ID + 1 }], "Expense partner preflight was incomplete"],
    ])("does not POST on failed %s preflight", async (categories, partners, message) => {
        fetchMock.mockResolvedValueOnce(json(categories)).mockResolvedValueOnce(json(partners));
        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(data)).rejects.toThrow(message);
        expect(fetchMock).toHaveBeenCalledTimes(2);
    });

    test.each([
        ["missing line", report({ memo: "Multi", breakdowns: [data.businessBreakdowns[0]] })],
        ["unexpected line", report({ memo: "Multi", breakdowns: [...data.businessBreakdowns, { amount: 1, categoryId: 903 }] })],
        ["duplicate line", report({ memo: "Multi", breakdowns: [{ amount: 4.01, categoryId: 901 }, { amount: 4.01, categoryId: 901 }] })],
        ["errors", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { errors: ["bad"] })],
        ["message", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { message: "bad" })],
        ["unbalanced", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { allowUnbalanced: true })],
        ["invalid total", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { isTotalAmountValid: false })],
        ["validated", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { validated: true })],
        ["validated timestamp", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { validatedAt: "2025-01-15T00:00:00.000Z" })],
        ["date lock", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { lockedByDate: true })],
        ["manual lock", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { manuallyLocked: true })],
        ["attention", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { needsAttention: true })],
        ["draft", report({ memo: "Multi", breakdowns: data.businessBreakdowns }, { isDraft: true })],
    ])("fails closed without replay for %s provider responses", async (_name, response) => {
        fetchMock
            .mockResolvedValueOnce(json([901, 902]))
            .mockResolvedValueOnce(json([{ id: 1001, companyId: COMPANY_ID }]))
            .mockResolvedValueOnce(json(response));
        await expect(client().api.operations({ companyId: COMPANY_ID }).createExpenseReport(data))
            .rejects.toThrow(EXPENSE_REPORT_UNVERIFIED_POST);
        expect(fetchMock.mock.calls.filter(([, init]) => init.method === "POST")).toHaveLength(1);
    });

    test("exposes a strict CREATE action without provider-owned input fields", () => {
        expect(actions.operations_create_expense_report.safety).toEqual({
            readOnly: false, destructive: false, idempotent: false, openWorld: true,
        });
        expect(actions.operations_create_expense_report.inputSchema.safeParse({
            companyId: COMPANY_ID, data: { ...data, amount: 10.01 },
        }).success).toBe(false);
        expect(actions.operations_create_expense_report.inputSchema.safeParse({
            companyId: COMPANY_ID, data: { ...data, businessBreakdowns: [...data.businessBreakdowns, { amount: 1, categoryId: 901 }] },
        }).success).toBe(false);
    });
});
