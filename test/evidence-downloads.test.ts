import { Client, MAX_DOWNLOAD_BYTES } from "../src";

const BASE_URL = "https://app.dougs.fr";
const INVOICE_ID = "00000000-0000-4000-8000-000000000001";

function createClient(): Client {
    return new Client({
        email: "test@example.invalid",
        password: "not-a-real-password",
        baseUrl: BASE_URL,
        cookies: ["session=test-cookie"],
    });
}

describe("evidence downloads", () => {
    const realFetch = global.fetch;
    let fetchMock: jest.Mock;

    beforeEach(() => {
        fetchMock = jest.fn();
        global.fetch = fetchMock as unknown as typeof fetch;
    });

    afterEach(() => {
        global.fetch = realFetch;
    });

    test("downloads purchase evidence from the invoice metadata filePath", async () => {
        fetchMock
            .mockResolvedValueOnce(new Response(JSON.stringify({
                id: INVOICE_ID,
                filePath: "/files/evidence/download",
            }), { status: 200 }))
            .mockResolvedValueOnce(new Response("invoice evidence", {
                status: 200,
                headers: {
                    "content-type": "application/pdf",
                    "content-disposition": "attachment; filename=invoice.pdf",
                },
            }));

        const download = await createClient().api.invoices({ companyId: 42 })
            .downloadPurchaseEvidence(INVOICE_ID);

        expect(download).toMatchObject({ contentType: "application/pdf", filename: "invoice.pdf" });
        expect(download.buffer.toString()).toBe("invoice evidence");
        expect(fetchMock.mock.calls.map(([url]) => String(url))).toEqual([
            `https://app.dougs.fr/companies/42/vendor-invoices/${INVOICE_ID}`,
            "https://app.dougs.fr/files/evidence/download",
        ]);
    });

    test.each([null, "   "])("rejects a purchase invoice with an unusable path without downloading", async (filePath) => {
        fetchMock.mockResolvedValueOnce(new Response(JSON.stringify({
            id: INVOICE_ID,
            filePath,
        }), { status: 200 }));

        await expect(createClient().api.invoices({ companyId: 42 })
            .downloadPurchaseEvidence(INVOICE_ID))
            .rejects.toThrow("no downloadable evidence");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("downloads an operation attachment selected from operation metadata", async () => {
        fetchMock
            .mockResolvedValueOnce(new Response(JSON.stringify({
                id: 7,
                date: "2025-01-01",
                amount: 10,
                type: "expense",
                isInbound: false,
                hasVat: false,
                deleted: false,
                isDraft: false,
                autogenerated: false,
                validated: false,
                excluded: false,
                sourceDocumentAttachments: [{ id: 9, url: "/source-documents/9/download" }],
            }), { status: 200 }))
            .mockResolvedValueOnce(new Response("attachment", {
                status: 200,
                headers: { "content-type": "image/jpeg" },
            }));

        const download = await createClient().api.operations({ companyId: 42 })
            .downloadSourceDocumentAttachment(7, 9);

        expect(download.buffer.toString()).toBe("attachment");
        expect(download.contentType).toBe("image/jpeg");
        expect(fetchMock.mock.calls.map(([url]) => String(url))).toEqual([
            "https://app.dougs.fr/companies/42/operations/7",
            "https://app.dougs.fr/source-documents/9/download",
        ]);
    });

    test("downloads the current nested sourceDocument.file response while retaining attachment identity", async () => {
        fetchMock
            .mockResolvedValueOnce(new Response(JSON.stringify({
                id: 7, companyId: 42, date: "2026-01-12", amount: 738.96,
                type: "bank", isInbound: false, hasVat: false,
                deleted: false, isDraft: false, autogenerated: false, validated: false, excluded: false,
                sourceDocumentAttachments: [{ id: 9, isDeletable: true, sourceDocument: {
                    id: 10, companyId: 42, file: { id: "file-id", name: "appel.pdf", url: "/files/file-id/actions/download", mimeType: "application/pdf", createdAt: "2026-01-01T00:00:00Z" },
                } }],
            }), { status: 200 }))
            .mockResolvedValueOnce(new Response("%PDF-test", { status: 200, headers: { "content-type": "application/pdf" } }));
        const download = await createClient().api.operations({ companyId: 42 }).downloadSourceDocumentAttachment(7, 9);
        expect(download.buffer.toString()).toBe("%PDF-test");
        expect(download.contentType).toBe("application/pdf");
        expect(fetchMock.mock.calls.map(([url]) => String(url))).toEqual([
            "https://app.dougs.fr/companies/42/operations/7", "https://app.dougs.fr/files/file-id/actions/download",
        ]);
    });

    test.each([null, {}, { file: null }, { file: { url: 12 } }, { file: { url: " " } }])("rejects unusable nested attachment metadata", async (sourceDocument) => {
        fetchMock.mockResolvedValueOnce(new Response(JSON.stringify({
            id: 7, date: "2026-01-12", amount: 10, type: "bank", isInbound: false,
            hasVat: false, deleted: false, isDraft: false, autogenerated: false, validated: false, excluded: false,
            sourceDocumentAttachments: [{ id: 9, sourceDocument }],
        }), { status: 200 }));
        await expect(createClient().api.operations({ companyId: 42 }).downloadSourceDocumentAttachment(7, 9))
            .rejects.toThrow("no matching source-document attachment");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test.each([undefined, null, "   "])("rejects an operation attachment with an unusable URL", async (url) => {
        fetchMock.mockResolvedValueOnce(new Response(JSON.stringify({
            id: 7,
            date: "2025-01-01",
            amount: 10,
            type: "expense",
            isInbound: false,
            hasVat: false,
            deleted: false,
            isDraft: false,
            autogenerated: false,
            validated: false,
            excluded: false,
            sourceDocumentAttachments: [{ id: 9, url }],
        }), { status: 200 }));

        await expect(createClient().api.operations({ companyId: 42 })
            .downloadSourceDocumentAttachment(7, 9))
            .rejects.toThrow("no matching source-document attachment");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("rejects an absent operation attachment without requesting a download", async () => {
        fetchMock.mockResolvedValueOnce(new Response(JSON.stringify({
            id: 7,
            date: "2025-01-01",
            amount: 10,
            type: "expense",
            isInbound: false,
            hasVat: false,
            deleted: false,
            isDraft: false,
            autogenerated: false,
            validated: false,
            excluded: false,
            sourceDocumentAttachments: [],
        }), { status: 200 }));

        await expect(createClient().api.operations({ companyId: 42 })
            .downloadSourceDocumentAttachment(7, 9))
            .rejects.toThrow("no matching source-document attachment");
        expect(fetchMock).toHaveBeenCalledTimes(1);
    });

    test("rejects unsafe direct invoice endpoint IDs before a path is built", async () => {
        const invoices = createClient().api.invoices({ companyId: 42 });

        expect(() => invoices.getPurchase("../other-resource")).toThrow("Invalid invoice identifier");
        expect(() => invoices.getSale("../other-resource")).toThrow("Invalid invoice identifier");
        expect(fetchMock).not.toHaveBeenCalled();
    });

    test("rejects declared oversized downloads before consuming their body", async () => {
        const cancel = jest.fn().mockResolvedValue(undefined);
        const getReader = jest.fn();
        fetchMock.mockResolvedValueOnce({
            status: 200,
            ok: true,
            headers: new Headers({ "content-length": String(MAX_DOWNLOAD_BYTES + 1) }),
            body: { cancel, getReader },
        } as unknown as Response);

        await expect(createClient().downloadFile("/files/synthetic-download"))
            .rejects.toThrow("file exceeds the maximum size");
        expect(getReader).not.toHaveBeenCalled();
        expect(cancel).toHaveBeenCalledTimes(1);
    });

    test("rejects streamed downloads that exceed the cap despite a lying Content-Length", async () => {
        const cancel = jest.fn();
        const body = new ReadableStream<Uint8Array>({
            start(controller) {
                controller.enqueue(new Uint8Array(MAX_DOWNLOAD_BYTES));
                controller.enqueue(new Uint8Array([1]));
            },
            cancel,
        });
        fetchMock.mockResolvedValueOnce(new Response(body, {
            status: 200,
            headers: { "content-length": "1" },
        }));

        await expect(createClient().downloadFile("/files/synthetic-download"))
            .rejects.toThrow("file exceeds the maximum size");
        expect(cancel).toHaveBeenCalled();
    });

    test("accepts a streamed download exactly at the cap", async () => {
        fetchMock.mockResolvedValueOnce(new Response(new Uint8Array(MAX_DOWNLOAD_BYTES), { status: 200 }));

        const download = await createClient().downloadFile("/files/synthetic-download");

        expect(download.buffer.byteLength).toBe(MAX_DOWNLOAD_BYTES);
    });

    test("returns an empty file when a successful response has no body", async () => {
        fetchMock.mockResolvedValueOnce(new Response(null, { status: 200 }));

        const download = await createClient().downloadFile("/files/synthetic-download");

        expect(download.buffer).toEqual(Buffer.alloc(0));
    });
});
